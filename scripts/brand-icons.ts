// Generates every site icon in industry/brand/ from the brand masters in industry/brand/source/ (the five-arm
// galaxy, DEC-78 supplement 2026-11-04), so no icon is drawn by hand and none drifts from the masters:
// - the ivory app icon: logo.svg, icon.png (512) and icon-192.png (web manifest), icon-96.png (page head: Google's
//   favicon in search results, a multiple of 48 px) and icon-144.png (RSS channel image, at most 144 px wide);
// - the same icon as a full opaque square, for platforms that cut their own shape: apple-icon.png (180; Apple rounds
//   touch icons itself) and icon-maskable.png (512; Android launchers mask it, the mark stays in the safe zone);
// - the deeper small mark for the 16–48 px favicon.ico.
// tests/site-icons.test.ts checks the files against these renders and against what the page head, the web
// manifest, the RSS feeds and the structured data declare.
//
// Usage: node scripts/brand-icons.ts
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const BRAND = path.join(import.meta.dirname, "../industry/brand");

const png = (svg: string, px: number) =>
  sharp(Buffer.from(svg), { density: 72 * Math.ceil(px / 48) * 4 })
    .resize(px, px)
    .png({ compressionLevel: 9 })
    .toBuffer();

/** The app icon with its ivory ground run to the square's edges and without the hairline border; the mark is unchanged. */
function fullSquare(svg: string): string {
  const ground = /<rect width="64" height="64" rx="[\d.]+" fill="url\(#bg\)"\/>/;
  const border = /<rect [^>]*fill="none" stroke="[^"]*"[^>]*\/>/;
  if (!ground.test(svg) || !border.test(svg)) throw new Error("industry/brand/source/app-icon.svg: expected its rounded ivory ground and hairline border");
  return svg.replace(ground, '<rect width="64" height="64" fill="url(#bg)"/>').replace(border, "");
}

/** favicon.ico: 16, 32 and 48 pixel PNGs of the small mark behind one icon directory. */
async function favicon(smallMark: string): Promise<Buffer> {
  const sizes = [16, 32, 48];
  const images = await Promise.all(sizes.map((px) => png(smallMark, px)));
  const directory = Buffer.alloc(6 + 16 * sizes.length);
  directory.writeUInt16LE(1, 2); // type: icon
  directory.writeUInt16LE(sizes.length, 4);
  let offset = directory.length;
  sizes.forEach((px, i) => {
    const entry = 6 + 16 * i;
    directory.writeUInt8(px, entry);
    directory.writeUInt8(px, entry + 1);
    directory.writeUInt16LE(1, entry + 4); // colour planes
    directory.writeUInt16LE(32, entry + 6); // bits per pixel
    directory.writeUInt32LE(images[i]!.length, entry + 8);
    directory.writeUInt32LE(offset, entry + 12);
    offset += images[i]!.length;
  });
  return Buffer.concat([directory, ...images]);
}

/** Every icon file this script makes, by its name in industry/brand/, rendered from the masters. */
export async function brandIcons(): Promise<Record<string, Buffer>> {
  const appIcon = readFileSync(path.join(BRAND, "source/app-icon.svg"), "utf8");
  const smallMark = readFileSync(path.join(BRAND, "source/mark-small.svg"), "utf8");
  const square = fullSquare(appIcon);
  /** Opaque, flattened onto the ivory ground. */
  const opaque = async (px: number) =>
    sharp(await png(square, px))
      .flatten({ background: "#F6F0E3" })
      .png({ compressionLevel: 9 })
      .toBuffer();
  return {
    "logo.svg": Buffer.from(`<!-- Generated by scripts/brand-icons.ts from industry/brand/source/app-icon.svg. -->\n${appIcon}`),
    "icon.png": await png(appIcon, 512),
    "icon-192.png": await png(appIcon, 192),
    "icon-144.png": await png(appIcon, 144),
    "icon-96.png": await png(appIcon, 96),
    "apple-icon.png": await opaque(180),
    "icon-maskable.png": await opaque(512),
    "favicon.ico": await favicon(smallMark),
  };
}

if (import.meta.main) {
  const icons = await brandIcons();
  for (const [file, body] of Object.entries(icons)) writeFileSync(path.join(BRAND, file), body);
  console.log("industry/brand", { files: Object.keys(icons) });
}
