// Generates the site icons in industry/brand/ (logo.svg, icon.png, icon-192.png, apple-icon.png and favicon.ico)
// from the brand masters in industry/brand/source/ (the five-arm galaxy, DEC-78 supplement 2026-11-04):
// the ivory app icon for logo.svg and the touch icons, the deeper small mark for the 16–48 px favicon.
//
// Usage: node scripts/brand-icons.ts
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const target = "industry/brand";
const appIcon = readFileSync(`${target}/source/app-icon.svg`, "utf8");
const smallMark = readFileSync(`${target}/source/mark-small.svg`, "utf8");
const png = (source: string, px: number) =>
  sharp(Buffer.from(source), { density: 72 * Math.ceil(px / 48) * 4 })
    .resize(px, px)
    .png({ compressionLevel: 9 })
    .toBuffer();

writeFileSync(`${target}/logo.svg`, `<!-- Generated by scripts/brand-icons.ts from industry/brand/source/app-icon.svg. -->\n${appIcon}`);
writeFileSync(`${target}/icon.png`, await png(appIcon, 512));
writeFileSync(`${target}/icon-192.png`, await png(appIcon, 192));
// Apple rounds touch icons itself and wants them square and opaque: flatten the rounded corners onto the ivory ground.
writeFileSync(
  `${target}/apple-icon.png`,
  await sharp(await png(appIcon, 180))
    .flatten({ background: "#F6F0E3" })
    .png({ compressionLevel: 9 })
    .toBuffer(),
);

// favicon.ico: 16, 32 and 48 pixel PNGs of the small mark behind one icon directory.
const sizes = [16, 32, 48];
const images = await Promise.all(sizes.map((px) => png(smallMark, px)));
const directory = Buffer.alloc(6 + 16 * sizes.length);
directory.writeUInt16LE(1, 2); // type: icon
directory.writeUInt16LE(sizes.length, 4);
let offset = directory.length;
sizes.forEach((px, i) => {
  const entry = 6 + 16 * i;
  directory.writeUInt8(px, entry);
  directory.writeUInt8(px, entry + 1);
  directory.writeUInt16LE(1, entry + 4); // colour planes
  directory.writeUInt16LE(32, entry + 6); // bits per pixel
  directory.writeUInt32LE(images[i]!.length, entry + 8);
  directory.writeUInt32LE(offset, entry + 12);
  offset += images[i]!.length;
});
writeFileSync(`${target}/favicon.ico`, Buffer.concat([directory, ...images]));
console.log(target, { files: ["logo.svg", "icon.png", "icon-192.png", "apple-icon.png", "favicon.ico"] });
