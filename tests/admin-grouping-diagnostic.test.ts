import "./setup.ts";
import assert from "node:assert/strict";
import { after, test } from "node:test";
import { randomUUID } from "node:crypto";
import { dbOf, closeDb } from "@amp/backend/db";
import { upsertMaterial } from "@amp/backend/content/materials";
import { contentChain } from "@amp/backend/admin/content";
import { beginMaterialGrouping, completeMaterialGrouping, failMaterialGrouping } from "../packages/backend/src/content/grouping.ts";
import { NewsGroupingDiagnostic } from "@amp/contracts/http/private";
const sql = dbOf("content");
after(closeDb);

test("admin diagnostics distinguish scoring nomination, current grouping, no new value and material revision", async () => {
  const sourceId = `diag-${randomUUID()}`;
  await sql`INSERT INTO sources(id,name,kind) VALUES(${sourceId},'合成诊断来源','rss')`;
  const material = { sourceId, url: `https://example.invalid/${sourceId}`, title: "矿企合成公告", bodyText: "初始材料", via: "fetch" as const };
  const { articleId } = await upsertMaterial(material);
  await sql`UPDATE articles SET grouped_at=now() WHERE id=${articleId}`;
  let result = (await contentChain(articleId))!;
  assert.equal(result.grouping!.status, "pending");
  assert.equal(result.grouping!.selectionCandidate, null);
  assert.equal(result.grouping!.addsValue, null);
  await sql`INSERT INTO analyses(article_id,input_revision,origin,score,selected) VALUES(${articleId},1,'rule',88,true)`;
  result = (await contentChain(articleId))!;
  assert.equal(result.grouping!.selectionCandidate, true);
  assert.equal(result.grouping!.status, "pending", "passing scores do not mean confirmed selection");
  await completeMaterialGrouping(articleId, 1, { addsValue: false, reason: "已报道相同事实，没有新增信息" }, null);
  result = (await contentChain(articleId))!;
  assert.ok(NewsGroupingDiagnostic.safeParse(result.grouping).success);
  assert.equal(result.grouping!.status, "complete");
  assert.equal(result.grouping!.addsValue, false);
  assert.match(result.grouping!.reason!, /没有新增信息/);
  await upsertMaterial({ ...material, bodyText: "修订后的真实材料" });
  result = (await contentChain(articleId))!;
  assert.equal(result.grouping!.materialRevision, 2);
  assert.equal(result.grouping!.status, "pending");
  assert.equal(result.grouping!.selectionCandidate, null);
  assert.equal(result.grouping!.reason, null);
  await failMaterialGrouping(articleId, 2, { waiting: false, receiptId: null, error: "合成输出缺少候选答案" });
  result = (await contentChain(articleId))!;
  assert.equal(result.grouping!.status, "failed");
  assert.match(result.grouping!.error!, /缺少候选答案/);
  await beginMaterialGrouping(articleId, 2, true);
  result = (await contentChain(articleId))!;
  assert.equal(result.grouping!.status, "pending");
  assert.equal(result.grouping!.error, null);
  await sql`UPDATE articles SET grouping_status='complete',grouping_input_revision=1,selection_adds_value=true,selection_value_reason='旧版本判断' WHERE id=${articleId}`;
  result = (await contentChain(articleId))!;
  assert.equal(result.grouping!.status, "pending");
  assert.equal(result.grouping!.addsValue, null);
  assert.equal(result.grouping!.reason, null);
});
