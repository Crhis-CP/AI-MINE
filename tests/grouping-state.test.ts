import { tag } from "./setup.ts";
import { after, test } from "node:test";
import assert from "node:assert/strict";
import { dbOf, closeDb } from "@amp/backend/db";
import { upsertMaterial } from "@amp/backend/content/materials";
import { readMaterialGrouping, beginMaterialGrouping, completeMaterialGrouping, failMaterialGrouping } from "../packages/backend/src/content/grouping.ts";
const sql = dbOf("content");
after(closeDb);
test("legacy grouping timestamps never confirm a current decision and stale writes cannot finish it", async () => {
  const sourceId = `group-state-${tag()}`;
  await sql`INSERT INTO sources(id,name,kind) VALUES(${sourceId},'合成来源','rss')`;
  const material = { sourceId, url: `https://example.com/${sourceId}`, title: "矿企公告", bodyText: "第一版矿企公告", via: "fetch" as const };
  const { articleId } = await upsertMaterial(material);
  await sql`UPDATE articles SET grouped_at=now() WHERE id=${articleId}`;
  assert.equal((await readMaterialGrouping(articleId))?.grouping_status, "pending");
  assert.equal((await readMaterialGrouping(articleId))?.selection_adds_value, null);
  assert.equal(await beginMaterialGrouping(articleId, 1), true);
  assert.equal(await completeMaterialGrouping(articleId, 1, { addsValue: false, reason: "已经报道，没有新增信息" }, null), true);
  assert.equal(await beginMaterialGrouping(articleId, 1), false, "a duplicate job preserves completed work");
  assert.equal(await failMaterialGrouping(articleId, 1, { waiting: false, receiptId: null, error: "late failed job" }), false);
  assert.equal((await readMaterialGrouping(articleId))?.selection_adds_value, false);
  await upsertMaterial({ ...material, bodyText: "第二版真实修订公告" });
  assert.equal((await readMaterialGrouping(articleId))?.grouping_status, "pending");
  assert.equal((await readMaterialGrouping(articleId))?.selection_adds_value, null);
  assert.equal(await completeMaterialGrouping(articleId, 1, { addsValue: true, reason: "过时答案" }, null), false);
  assert.equal(await beginMaterialGrouping(articleId, 2), true);
  assert.equal(await failMaterialGrouping(articleId, 2, { waiting: true, receiptId: null, error: "等待服务窗口" }), true);
  assert.equal((await readMaterialGrouping(articleId))?.selection_adds_value, null);
  assert.equal(await completeMaterialGrouping(articleId, 2, { addsValue: true, reason: "披露了新的进展" }, null), true);
  const current = await readMaterialGrouping(articleId);
  assert.equal(current?.grouping_input_revision, 2);
  assert.equal(current?.grouping_status, "complete");
  assert.equal(await beginMaterialGrouping(articleId, 2, true), true, "an explicit regroup clears prior value");
  assert.equal((await readMaterialGrouping(articleId))?.selection_adds_value, null);
});
